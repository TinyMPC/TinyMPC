/* Define the maximum allowed length of the path (directory + filename + extension) */
#define PATH_LENGTH 2048

using namespace Eigen;

static void create_directory(const char* dir, int verbose) {
    // Attempt to create directory
    if (mkdir(dir, S_IRWXU|S_IRWXG|S_IROTH)) {
        if (errno == EEXIST) { // Skip if directory already exists
            if (verbose)
                std::cout << dir << " already exists, skipping." << std::endl;
        } else {
            ERROR_MSG(EXIT_FAILURE, "Failed to create directory %s", dir);
        }
    }
}

// TODO: Make this fail if tiny_setup has not already been called
int tiny_codegen(TinySolver* solver, const char* output_dir, int verbose) {
    if (!solver) {
        std::cout << "Error in tiny_codegen: solver is nullptr" << std::endl;
        return 1;
    }
    int status = 0;
    status |= codegen_create_directories(output_dir, verbose);
    status |= codegen_data_header(output_dir, verbose);
    status |= codegen_data_source(solver, output_dir, verbose);
    status |= codegen_example(output_dir, verbose);

    return status;
}

int tiny_codegen_with_sensitivity(TinySolver* solver, const char* output_dir,
                                tinyMatrix* dK, tinyMatrix* dP,
                                tinyMatrix* dC1, tinyMatrix* dC2, int verbose) {
    if (!solver) {
        std::cout << "Error in tiny_codegen_with_sensitivity: solver is nullptr" << std::endl;
        return 1;
    }

    // Only store sensitivity matrices if adaptive rho is enabled
    if (solver->settings->adaptive_rho) {
        // Store the sensitivity matrices in the solver's cache
        solver->cache->dKinf_drho = *dK;
        solver->cache->dPinf_drho = *dP;
        solver->cache->dC1_drho = *dC1;
        solver->cache->dC2_drho = *dC2;
    }

    // Call the regular codegen function which will now include the sensitivity matrices if adaptive_rho is enabled
    return tiny_codegen(solver, output_dir, verbose);
}

// Create code generation folder structure in whichever directory the executable calling tiny_codegen was called
int codegen_create_directories(const char* output_dir, int verbose) {

    // Create output folder (root folder for code generation)
    create_directory(output_dir, verbose);

    // Create src folder
    char src_dir[PATH_LENGTH];
    sprintf(src_dir, "%s/src/", output_dir);
    create_directory(src_dir, verbose);

    // Create tinympc folder
    char tinympc_dir[PATH_LENGTH];
    sprintf(tinympc_dir, "%s/tinympc/", output_dir);
    create_directory(tinympc_dir, verbose);

    // // Create include folder
    // char inc_dir[PATH_LENGTH];
    // sprintf(inc_dir, "%s/include/", output_dir);
    // create_directory(inc_dir, verbose);

    return EXIT_SUCCESS;
}

// Create inc/tiny_data.hpp file
int codegen_data_header(const char* output_dir, int verbose) {
    char data_hpp_fname[PATH_LENGTH];
    FILE *data_hpp_f;

    sprintf(data_hpp_fname, "%s/tinympc/tiny_data.hpp", output_dir);

    // Open data header file
    data_hpp_f = fopen(data_hpp_fname, "w+");
    if (data_hpp_f == NULL)
        ERROR_MSG(EXIT_FAILURE, "Failed to open file %s", data_hpp_fname);
    
    // Preamble
    time_t start_time;
    time(&start_time);
    fprintf(data_hpp_f, "/*\n");
    fprintf(data_hpp_f, " * This file was autogenerated by TinyMPC on %s", ctime(&start_time));
    fprintf(data_hpp_f, " */\n\n");

    fprintf(data_hpp_f, "#pragma once\n\n");

    fprintf(data_hpp_f, "#include \"types.hpp\"\n\n");

    fprintf(data_hpp_f, "#ifdef __cplusplus\n");
    fprintf(data_hpp_f, "extern \"C\" {\n");
    fprintf(data_hpp_f, "#endif\n\n");

    fprintf(data_hpp_f, "extern TinySolver tiny_solver;\n\n");

    fprintf(data_hpp_f, "#ifdef __cplusplus\n");
    fprintf(data_hpp_f, "}\n");
    fprintf(data_hpp_f, "#endif\n");

    // Close codegen data header file
    fclose(data_hpp_f);

    if (verbose) {
        printf("Data header generated in %s\n", data_hpp_fname);
    }
    return 0;
}

// Helpers that emit "<name> = <value>;" assignments. Assigning fields by name
// (instead of positional aggregate initialization) keeps the generated code
// correct when fields are added to or reordered in the structs in types.hpp.
static void emit_matrix(FILE *f, const char* name, const MatrixXd& mat)
{
    if (mat.size() == 0) {
        fprintf(f, "\t%s = tinyMatrix::Zero(%ld, %ld);\n", name, (long)mat.rows(), (long)mat.cols());
        return;
    }
    fprintf(f, "\t%s = (tinyMatrix(%ld, %ld) << ", name, (long)mat.rows(), (long)mat.cols());
    for (Index i = 0; i < mat.size(); i++) {
        fprintf(f, "(tinytype)%.17g", mat.reshaped<RowMajor>()[i]);
        if (i < mat.size() - 1)
            fprintf(f, ",");
    }
    fprintf(f, ").finished();\n");
}

static void emit_zero_matrix(FILE *f, const char* name, const MatrixXd& like)
{
    fprintf(f, "\t%s = tinyMatrix::Zero(%ld, %ld);\n", name, (long)like.rows(), (long)like.cols());
}

static void emit_vector(FILE *f, const char* name, const VectorXd& vec)
{
    if (vec.size() == 0) {
        fprintf(f, "\t%s = tinyVector::Zero(0);\n", name);
        return;
    }
    fprintf(f, "\t%s = (tinyVector(%ld) << ", name, (long)vec.size());
    for (Index i = 0; i < vec.size(); i++) {
        fprintf(f, "(tinytype)%.17g", vec[i]);
        if (i < vec.size() - 1)
            fprintf(f, ",");
    }
    fprintf(f, ").finished();\n");
}

static void emit_zero_vector(FILE *f, const char* name, const VectorXd& like)
{
    fprintf(f, "\t%s = tinyVector::Zero(%ld);\n", name, (long)like.size());
}

static void emit_vectori(FILE *f, const char* name, const VectorXi& vec)
{
    if (vec.size() == 0) {
        fprintf(f, "\t%s = VectorXi::Zero(0);\n", name);
        return;
    }
    fprintf(f, "\t%s = (VectorXi(%ld) << ", name, (long)vec.size());
    for (Index i = 0; i < vec.size(); i++) {
        fprintf(f, "%d", vec[i]);
        if (i < vec.size() - 1)
            fprintf(f, ",");
    }
    fprintf(f, ").finished();\n");
}

static void emit_int(FILE *f, const char* name, int val)
{
    fprintf(f, "\t%s = %d;\n", name, val);
}

static void emit_scalar(FILE *f, const char* name, tinytype val)
{
    fprintf(f, "\t%s = (tinytype)%.17g;\n", name, (double)val);
}

// Create src/tiny_data.cpp file
int codegen_data_source(TinySolver* solver, const char* output_dir, int verbose) {
    char data_cpp_fname[PATH_LENGTH];
    FILE *data_cpp_f;

    TinySolution *sol = solver->solution;
    TinySettings *stgs = solver->settings;
    TinyCache *cache = solver->cache;
    TinyWorkspace *work = solver->work;

    sprintf(data_cpp_fname, "%s/src/tiny_data.cpp", output_dir);

    // Open data source file
    data_cpp_f = fopen(data_cpp_fname, "w+");
    if (data_cpp_f == NULL)
        ERROR_MSG(EXIT_FAILURE, "Failed to open file %s", data_cpp_fname);
    FILE *f = data_cpp_f;

    // Preamble
    time_t start_time;
    time(&start_time);
    fprintf(f, "/*\n");
    fprintf(f, " * This file was autogenerated by TinyMPC on %s", ctime(&start_time));
    fprintf(f, " */\n\n");

    // Open extern C
    fprintf(f, "#include \"tinympc/tiny_data.hpp\"\n\n");
    fprintf(f, "#ifdef __cplusplus\n");
    fprintf(f, "extern \"C\" {\n");
    fprintf(f, "#endif\n\n");

    fprintf(f, "TinySolution solution{};\n");
    fprintf(f, "TinySettings settings{};\n");
    fprintf(f, "TinyCache cache{};\n");
    fprintf(f, "TinyWorkspace work{};\n\n");
    fprintf(f, "TinySolver tiny_solver = {&solution, &settings, &cache, &work};\n\n");

    fprintf(f, "static int tiny_data_init()\n{\n");

    // Solution (zeros, sized like the solver's)
    fprintf(f, "\t/* Solution */\n");
    emit_int(f, "solution.iter", 0);
    emit_int(f, "solution.solved", 0);
    emit_zero_matrix(f, "solution.x", sol->x);
    emit_zero_matrix(f, "solution.u", sol->u);

    // Settings
    fprintf(f, "\n\t/* User settings */\n");
    emit_scalar(f, "settings.abs_pri_tol", stgs->abs_pri_tol);
    emit_scalar(f, "settings.abs_dua_tol", stgs->abs_dua_tol);
    emit_int(f, "settings.max_iter", stgs->max_iter);
    emit_int(f, "settings.check_termination", stgs->check_termination);
    emit_int(f, "settings.en_state_bound", stgs->en_state_bound);
    emit_int(f, "settings.en_input_bound", stgs->en_input_bound);
    emit_int(f, "settings.en_state_soc", stgs->en_state_soc);
    emit_int(f, "settings.en_input_soc", stgs->en_input_soc);
    emit_int(f, "settings.en_state_linear", stgs->en_state_linear);
    emit_int(f, "settings.en_input_linear", stgs->en_input_linear);
    emit_int(f, "settings.en_tv_state_linear", stgs->en_tv_state_linear);
    emit_int(f, "settings.en_tv_input_linear", stgs->en_tv_input_linear);
    emit_int(f, "settings.adaptive_rho", stgs->adaptive_rho);
    emit_scalar(f, "settings.adaptive_rho_min", stgs->adaptive_rho_min);
    emit_scalar(f, "settings.adaptive_rho_max", stgs->adaptive_rho_max);
    emit_int(f, "settings.adaptive_rho_enable_clipping", stgs->adaptive_rho_enable_clipping);

    // Cache
    fprintf(f, "\n\t/* Matrices that must be recomputed with changes in time step, rho */\n");
    emit_scalar(f, "cache.rho", cache->rho);
    emit_matrix(f, "cache.Kinf", cache->Kinf);
    emit_matrix(f, "cache.Pinf", cache->Pinf);
    emit_matrix(f, "cache.Quu_inv", cache->Quu_inv);
    emit_matrix(f, "cache.AmBKt", cache->AmBKt);
    emit_vector(f, "cache.APf", cache->APf);
    emit_vector(f, "cache.BPf", cache->BPf);
    emit_matrix(f, "cache.C1", cache->C1);
    emit_matrix(f, "cache.C2", cache->C2);
    if (stgs->adaptive_rho) {
        emit_matrix(f, "cache.dKinf_drho", cache->dKinf_drho);
        emit_matrix(f, "cache.dPinf_drho", cache->dPinf_drho);
        emit_matrix(f, "cache.dC1_drho", cache->dC1_drho);
        emit_matrix(f, "cache.dC2_drho", cache->dC2_drho);
    }
    emit_int(f, "cache.rho_mult_x", cache->rho_mult_x);
    emit_int(f, "cache.rho_mult_u", cache->rho_mult_u);

    // Workspace
    fprintf(f, "\n\t/* Problem variables */\n");
    emit_int(f, "work.nx", work->nx);
    emit_int(f, "work.nu", work->nu);
    emit_int(f, "work.N", work->N);

    // ADMM iterates start at zero
    emit_zero_matrix(f, "work.x", work->x);
    emit_zero_matrix(f, "work.u", work->u);
    emit_zero_matrix(f, "work.q", work->q);
    emit_zero_matrix(f, "work.r", work->r);
    emit_zero_matrix(f, "work.p", work->p);
    emit_zero_matrix(f, "work.d", work->d);
    emit_zero_matrix(f, "work.v", work->v);
    emit_zero_matrix(f, "work.vnew", work->vnew);
    emit_zero_matrix(f, "work.z", work->z);
    emit_zero_matrix(f, "work.znew", work->znew);
    emit_zero_matrix(f, "work.g", work->g);
    emit_zero_matrix(f, "work.y", work->y);

    // Bound constraints
    emit_matrix(f, "work.x_min", work->x_min);
    emit_matrix(f, "work.x_max", work->x_max);
    emit_matrix(f, "work.u_min", work->u_min);
    emit_matrix(f, "work.u_max", work->u_max);

    // Second-order cone constraints
    emit_int(f, "work.numStateCones", work->numStateCones);
    emit_int(f, "work.numInputCones", work->numInputCones);
    emit_vector(f, "work.cx", work->cx);
    emit_vector(f, "work.cu", work->cu);
    emit_vectori(f, "work.Acx", work->Acx);
    emit_vectori(f, "work.Acu", work->Acu);
    emit_vectori(f, "work.qcx", work->qcx);
    emit_vectori(f, "work.qcu", work->qcu);
    emit_zero_matrix(f, "work.vc", work->vc);
    emit_zero_matrix(f, "work.vcnew", work->vcnew);
    emit_zero_matrix(f, "work.zc", work->zc);
    emit_zero_matrix(f, "work.zcnew", work->zcnew);
    emit_zero_matrix(f, "work.gc", work->gc);
    emit_zero_matrix(f, "work.yc", work->yc);

    // Linear constraints
    emit_int(f, "work.numStateLinear", work->numStateLinear);
    emit_int(f, "work.numInputLinear", work->numInputLinear);
    emit_matrix(f, "work.Alin_x", work->Alin_x);
    emit_vector(f, "work.blin_x", work->blin_x);
    emit_matrix(f, "work.Alin_u", work->Alin_u);
    emit_vector(f, "work.blin_u", work->blin_u);
    emit_zero_matrix(f, "work.vl", work->vl);
    emit_zero_matrix(f, "work.vlnew", work->vlnew);
    emit_zero_matrix(f, "work.zl", work->zl);
    emit_zero_matrix(f, "work.zlnew", work->zlnew);
    emit_zero_matrix(f, "work.gl", work->gl);
    emit_zero_matrix(f, "work.yl", work->yl);

    // Time-varying linear constraints
    emit_int(f, "work.numtvStateLinear", work->numtvStateLinear);
    emit_int(f, "work.numtvInputLinear", work->numtvInputLinear);
    emit_matrix(f, "work.tv_Alin_x", work->tv_Alin_x);
    emit_matrix(f, "work.tv_blin_x", work->tv_blin_x);
    emit_matrix(f, "work.tv_Alin_u", work->tv_Alin_u);
    emit_matrix(f, "work.tv_blin_u", work->tv_blin_u);
    emit_zero_matrix(f, "work.vl_tv", work->vl_tv);
    emit_zero_matrix(f, "work.vlnew_tv", work->vlnew_tv);
    emit_zero_matrix(f, "work.zl_tv", work->zl_tv);
    emit_zero_matrix(f, "work.zlnew_tv", work->zlnew_tv);
    emit_zero_matrix(f, "work.gl_tv", work->gl_tv);
    emit_zero_matrix(f, "work.yl_tv", work->yl_tv);

    // Problem data
    emit_vector(f, "work.Q", work->Q);
    emit_vector(f, "work.R", work->R);
    emit_matrix(f, "work.Adyn", work->Adyn);
    emit_matrix(f, "work.Bdyn", work->Bdyn);
    emit_vector(f, "work.fdyn", work->fdyn);
    emit_zero_matrix(f, "work.Xref", work->Xref);
    emit_zero_matrix(f, "work.Uref", work->Uref);
    emit_zero_vector(f, "work.Qu", work->Qu);

    // Solve status
    emit_scalar(f, "work.primal_residual_state", 0);
    emit_scalar(f, "work.primal_residual_input", 0);
    emit_scalar(f, "work.dual_residual_state", 0);
    emit_scalar(f, "work.dual_residual_input", 0);
    emit_int(f, "work.status", 0);
    emit_int(f, "work.iter", 0);

    fprintf(f, "\treturn 0;\n}\n\n");
    fprintf(f, "// Runs during static initialization, before main()\n");
    fprintf(f, "static int tiny_data_initialized = tiny_data_init();\n\n");

    // Close extern C
    fprintf(f, "#ifdef __cplusplus\n");
    fprintf(f, "}\n");
    fprintf(f, "#endif\n\n");

    // Close codegen data file
    fclose(data_cpp_f);
    if (verbose) {
        printf("Data generated in %s\n", data_cpp_fname);
    }
    return 0;
}

int codegen_example(const char* output_dir, int verbose) {
    char example_cpp_fname[PATH_LENGTH];
    FILE *example_cpp_f;

    sprintf(example_cpp_fname, "%s/src/tiny_main.cpp", output_dir);

    // Open example file
    example_cpp_f = fopen(example_cpp_fname, "w+");
    if (example_cpp_f == NULL)
        ERROR_MSG(EXIT_FAILURE, "Failed to open file %s", example_cpp_fname);

    // Preamble
    time_t start_time;
    time(&start_time);
    fprintf(example_cpp_f, "/*\n");
    fprintf(example_cpp_f, " * This file was autogenerated by TinyMPC on %s", ctime(&start_time));
    fprintf(example_cpp_f, " */\n\n");

    fprintf(example_cpp_f, "#include <iostream>\n\n");

    fprintf(example_cpp_f, "#include <tinympc/tiny_api.hpp>\n");
    fprintf(example_cpp_f, "#include <tinympc/tiny_data.hpp>\n\n");

    fprintf(example_cpp_f, "using namespace Eigen;\n");
    fprintf(example_cpp_f, "IOFormat TinyFmt(4, 0, \", \", \"\\n\", \"[\", \"]\");\n\n");

    fprintf(example_cpp_f, "#ifdef __cplusplus\n");
    fprintf(example_cpp_f, "extern \"C\" {\n");
    fprintf(example_cpp_f, "#endif\n\n");

    fprintf(example_cpp_f, "int main()\n");
    fprintf(example_cpp_f, "{\n");
    fprintf(example_cpp_f, "\tint exitflag = 1;\n");
    fprintf(example_cpp_f, "\t// Double check some data\n");
    fprintf(example_cpp_f, "\tstd::cout << \"rho: \" << tiny_solver.cache->rho << std::endl;\n");
    fprintf(example_cpp_f, "\tstd::cout << \"\\nmax iters: \" << tiny_solver.settings->max_iter << std::endl;\n");
    fprintf(example_cpp_f, "\tstd::cout << \"\\nState transition matrix:\\n\" << tiny_solver.work->Adyn.format(TinyFmt) << std::endl;\n");
    fprintf(example_cpp_f, "\tstd::cout << \"\\nInput/control matrix:\\n\" << tiny_solver.work->Bdyn.format(TinyFmt) << std::endl;\n\n");

    fprintf(example_cpp_f, "\t// Visit https://tinympc.org/ to see how to set the initial condition and update the reference trajectory.\n\n");

    fprintf(example_cpp_f, "\tstd::cout << \"\\nSolving...\\n\" << std::endl;\n\n");
    fprintf(example_cpp_f, "\texitflag = tiny_solve(&tiny_solver);\n\n");
    fprintf(example_cpp_f, "\tif (exitflag == 0) printf(\"Hooray! Solved with no error!\\n\");\n");
    fprintf(example_cpp_f, "\telse printf(\"Oops! Something went wrong!\\n\");\n");

    fprintf(example_cpp_f, "\treturn 0;\n");
    fprintf(example_cpp_f, "}\n\n");

    fprintf(example_cpp_f, "#ifdef __cplusplus\n");
    fprintf(example_cpp_f, "} /* extern \"C\" */\n");
    fprintf(example_cpp_f, "#endif\n");

    // Close codegen example main file
    fclose(example_cpp_f);
    if (verbose) {
        printf("Example tinympc main generated in %s\n", example_cpp_fname);
    }
    return 0;
}

